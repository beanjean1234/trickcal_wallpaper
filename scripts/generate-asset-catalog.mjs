import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, "..");
const iconRoot = path.join(projectRoot, "icons");
const generatedModulePath = path.join(projectRoot, "js", "assets.generated.js");
const supportedExtensions = new Set([".webp", ".png", ".jpg", ".jpeg"]);
const categoryOrder = ["요정", "용족", "유령", "수인", "엘프", "정령", "미스틱"];

function toDisplayName(fileName) {
  const stem = path.basename(fileName, path.extname(fileName)).replace(/[_-]+/g, " ").trim();
  if (!stem) return "이름 없는 이미지";
  return stem.replace(/(^|\s)([a-z])/g, (_, space, letter) => `${space}${letter.toUpperCase()}`);
}

async function collectImages(directory, relativeDirectory = "") {
  const entries = await readdir(directory, { withFileTypes: true });
  const assets = [];

  for (const entry of entries) {
    const relativePath = path.posix.join(relativeDirectory.replaceAll("\\", "/"), entry.name);
    const absolutePath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      assets.push(...await collectImages(absolutePath, relativePath));
      continue;
    }
    if (!entry.isFile() || !supportedExtensions.has(path.extname(entry.name).toLowerCase())) continue;

    const parts = relativePath.split("/");
    assets.push({
      category: parts.length > 1 ? parts[0] : "미분류",
      name: toDisplayName(entry.name),
      file: relativePath,
    });
  }
  return assets;
}

const assets = (await collectImages(iconRoot)).sort((left, right) => {
  const leftCategory = categoryOrder.indexOf(left.category);
  const rightCategory = categoryOrder.indexOf(right.category);
  const categoryDifference =
    (leftCategory < 0 ? categoryOrder.length : leftCategory) -
    (rightCategory < 0 ? categoryOrder.length : rightCategory);
  return categoryDifference || left.name.localeCompare(right.name, "ko");
});

const moduleSource = [
  "// Generated by scripts/generate-asset-catalog.mjs. Do not edit by hand.",
  `export const ICON_CATEGORIES = Object.freeze(${JSON.stringify(categoryOrder, null, 2)});`,
  `export const ICON_ASSETS = Object.freeze(${JSON.stringify(assets, null, 2)}.map(Object.freeze));`,
  "",
].join("\n");
await writeFile(generatedModulePath, moduleSource, "utf8");

console.log(`Generated ${assets.length} image entries.`);
